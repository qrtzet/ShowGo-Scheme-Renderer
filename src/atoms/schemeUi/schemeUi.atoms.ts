import {atom} from 'jotai';

/**
 * Поколение вёрстки экрана выбора мест в приложении.
 *
 * Схема живёт в вебвью и обновляется деплоем сразу у всех, а приложение
 * расходится через сторы неделями. Поэтому схема не может просто «стать
 * новой»: рядом с ней на экране нативные шапка, панель и футер, и у старых
 * сборок они другие.
 *
 * Договорились так: новая сборка присылает своё поколение сообщением, а
 * пока его нет — считаем, что приложение старое, и показываем прежнюю
 * вёрстку. Поэтому по умолчанию 1, а не 2.
 */
export const LEGACY_SCHEME_UI = 1;

export const schemeUiVersionAtom = atom<number>(LEGACY_SCHEME_UI);

/**
 * Фон экрана в приложении.
 *
 * В новой вёрстке схема стоит в одном столбце с нативной шапкой, и свой
 * серый фон вебвью читался бы полосой другого цвета сразу под карточкой
 * сеанса. Цвет присылает приложение: он свой у светлой и тёмной темы, и
 * угадывать его здесь — значит разойтись при первой же правке палитры.
 */
export const appBackgroundAtom = atom<string | null>(null);

/**
 * Цвет завесы над схемой, когда открыта модалка выбора сектора. Приходит
 * из приложения по той же причине: шапку и нижнюю панель гасит оно само,
 * и завеса должна быть ровно той же, иначе видно стык.
 */
export const appOverlayAtom = atom<string | null>(null);
