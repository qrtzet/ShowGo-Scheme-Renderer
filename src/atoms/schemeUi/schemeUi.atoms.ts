import {atom} from 'jotai';

/**
 * Поколение вёрстки экрана выбора мест в приложении.
 *
 * Схема живёт в вебвью и обновляется деплоем сразу у всех, а приложение
 * расходится через сторы неделями. Поэтому схема не может просто «стать
 * новой»: рядом с ней на экране нативные шапка, панель и футер, и у старых
 * сборок они другие.
 *
 * Договорились так: новая сборка присылает своё поколение сообщением, а
 * пока его нет — считаем, что приложение старое, и показываем прежнюю
 * вёрстку. Поэтому по умолчанию 1, а не 2.
 */
export const LEGACY_SCHEME_UI = 1;

export const schemeUiVersionAtom = atom<number>(LEGACY_SCHEME_UI);
